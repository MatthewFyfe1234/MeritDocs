"""The common MIMIC case types as their own set of projects, built by the hospital model without changing it.

    python models/hospital-subset/subset.py      # -> models/hospital-subset/out/*.sql, cases.json

Cases: every demo admission whose billing group (HCFA DRG) starts with one of a type's groups in subset.json, one spec
each (the whole stay in one phase), numbered by type then admission. The master spec and process stay those of
models/hospital: this folder adds projects only, so fixes to the master carry over on the next run.
How: it imports the hospital scripts and, inside this process only, hands them this case list in place of the test
cases (authored/test_cases.json) and points their output files here. Nothing in models/hospital is written.
Outputs (run order in README.md):
  specs.sql                   Results: the specs and their spec nodes
  assignments.sql             Network: team and individual assignments
  assignment_outputs.sql      Network: outputs
  execution_materials.sql     Network: material uses
  execution_properties.sql    Network: readings
  assignment_properties.sql   Network: reading requirements
"""
import collections
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
HOSPITAL = os.path.join(HERE, "..", "hospital")
OUT = os.path.join(HERE, "out")
sys.path.insert(0, HOSPITAL)

import case_to_sql                     # noqa: E402
import assignments_to_sql as A         # noqa: E402
from build_tree import rows            # noqa: E402


def subset_cases():
    sub = json.load(open(os.path.join(HERE, "subset.json"), encoding="utf-8-sig"))
    drg = {}
    for r in rows("hosp/drgcodes"):
        if r["drg_type"] == "HCFA":
            drg.setdefault(r["hadm_id"], r["description"])
    admissions = case_to_sql.context()["admissions"]
    cases = []
    for t in sub["types"]:
        for hadm in sorted(h for h, d in drg.items() if d.startswith(tuple(t["drg"]))):
            cases.append({"hadm_id": hadm, "type": t["name"],
                          "title": f"{sub['label']}, {t['name'].lower()}: {case_to_sql.title_of(hadm)}",
                          "phases": [{"phase": 1, "name": "Whole stay", "until": admissions[hadm]["dischtime"], "about": ""}]})
    return cases


class CaseList:
    """Stands in for the json module inside assignments_to_sql: reading the test cases gives this subset instead."""
    def __init__(self, cases):
        self.cases = cases

    def load(self, f, **kw):
        if os.path.basename(getattr(f, "name", "")) == "test_cases.json":
            f.close()
            return {"cases": self.cases}
        return json.load(f, **kw)

    def __getattr__(self, name):
        return getattr(json, name)


def main():
    os.makedirs(OUT, exist_ok=True)
    cases = subset_cases()
    types = collections.Counter(c["type"] for c in cases)
    about = f"{len(cases)} specs: " + ", ".join(f"{t} {n}" for t, n in types.items())

    # Specs (numbered as the assignment scripts number them: 1, 2, 3 ... in this list).
    specs = [dict(case_to_sql.build_spec(c["hadm_id"], c), order=i) for i, c in enumerate(cases, 1)]
    sql = case_to_sql.all_cases_sql(specs)
    sql = re.sub(r"^/\*.*?\*/", f"""/*
  The common case types (models/hospital-subset/subset.json): {about}. Each spec as it stands at the end of the stay,
  each spec node dated by its first appearance in the data (MIMIC's own date-shifted times).
  Generated by models/hospital-subset/subset.py; a summary is in cases.json beside this script. Run after the master
  care tree (models/hospital). Replaces earlier runs of these specs (by name; @Reset = 1). Set @Commit = 0 for a dry run.
*/""", sql, count=1, flags=re.S)
    with open(os.path.join(OUT, "specs.sql"), "w", encoding="utf-8") as f:
        f.write(sql)
    with open(os.path.join(OUT, "cases.json"), "w", encoding="utf-8") as f:
        json.dump([{"order": s["order"], "type": c["type"], "hadm_id": s["hadm_id"], "title": s["title"],
                    "nodes": sum(len(ph["nodes"]) for ph in s["phases"])} for s, c in zip(specs, cases)],
                  f, indent=1, ensure_ascii=False)
    print(f"{about}; {sum(len(ph['nodes']) for s in specs for ph in s['phases'])} spec nodes -> {OUT}", file=sys.stderr)

    # The project scripts, on this case list, writing here.
    A.json = CaseList(cases)
    import outputs_to_sql, materials_to_sql, readings_to_sql   # noqa: E401
    A.OUT = os.path.join(OUT, "assignments.sql")
    outputs_to_sql.OUT = os.path.join(OUT, "assignment_outputs.sql")
    materials_to_sql.OUT = os.path.join(OUT, "execution_materials.sql")
    readings_to_sql.OUT_READINGS = os.path.join(OUT, "execution_properties.sql")
    readings_to_sql.OUT_REQUIREMENTS = os.path.join(OUT, "assignment_properties.sql")
    readings_to_sql.OUT_PROPS = os.devnull   # the property definitions are the master's (models/hospital)
    for m in (A, outputs_to_sql, materials_to_sql, readings_to_sql):
        print(f"== {m.__name__}", file=sys.stderr)
        m.main()


if __name__ == "__main__":
    main()
