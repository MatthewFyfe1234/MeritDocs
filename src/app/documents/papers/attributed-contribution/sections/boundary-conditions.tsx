import { Cite } from '@/components/paper';

export function BoundaryConditions() {
  return (
    <>
      <h2>Boundary conditions</h2>
      <p>
        The boundary conditions fall into four groups, of scope, estimation, incentives, and governance and law.
      </p>

      <h3>Scope</h3>
      <p>
        <strong>Work that does not repeat.</strong> Forecasting and comparison depend on repeated delivery of the
        same step. Creative, bespoke and novel work produces few repetitions, so it has no forecast and no basis for
        comparison until it begins to repeat. Innovation on existing steps is not affected, since a new method is
        evaluated against the forecast of the step it delivers.
      </p>
      <p>
        <strong>Lagged and dispersed outcomes.</strong> Both examples are repetitive steps with immediate metrics. In
        construction, healthcare and supply chains, outcomes such as durability, recovery or carbon arrive late, are
        observed rarely for any combination of descriptor values, and depend on many earlier steps. Forecasts are then
        wider, and effects take more deliveries to separate. Linking records through the outputs that pass between
        steps relates a late outcome to the steps that preceded it, but separating their effects remains a question of
        causal inference beyond the model.
      </p>
      <p>
        <strong>Unrecorded dimensions.</strong> The multitask problem <Cite id="holmstrom1991" /> remains for
        dimensions not recorded as metrics, which will be neglected. Where reward or eligibility is computed from a
        score, the weights it applies are fixed again, and the problem returns for that use. A dimension unrecorded at one
        step may be recorded at a later one, where the output it affected is received as a material, which partly
        disciplines its neglect. Professors whose students scored higher in introductory courses have been found to
        have students who did worse in follow-on courses, a cost visible only downstream <Cite id="carrell2010" />. In
        software production, code written rose with coding agents without a matching rise in work completed, as
        review, the step that received it, absorbed the gain <Cite id="chen2026" />.
        How this composes across a network of steps is left to the companion construction. Recording more dimensions
        narrows the gap without closing it, and contribution that resists measurement remains on the conventional basis while measurable work
        advances.
      </p>

      <h3>Estimation</h3>
      <p>
        <strong>Choice of work.</strong> Where workers choose their work and the descriptors omit part of its
        difficulty, a worker can take instances easier than their descriptor values suggest and beat the forecast
        without contributing more, as providers avoided sicker patients under published report
        cards <Cite id="dranove2003" />. Effects are then biased toward those who choose well. Allocating a share of
        work rather than offering all of it for selection, and comparing performance on chosen and allocated work,
        reveals the bias, and richer descriptors reduce it.
      </p>
      <p>
        <strong>Integrity of capture.</strong> Capture lies outside the model, but the model makes it harder to
        game. The specification and its descriptors are set by a party other than the worker
        performing the step, and conditions of materials are often measured by instrument, as the combine measures
        the moisture of the crop. Records are independent
        of the agent&rsquo;s own account. Reconciliation exposes inconsistent records, and an output is corroborated
        when the next step or the client receives it. What remains is data that is wrong but consistent, which the
        model cannot detect. Where capture is manual, generative AI lowers the cost of fabricating a consistent
        record, so the record resists cheap claims most strongly where capture is instrumented. Instruments are not
        neutral either. Diesel vehicles that met emissions limits on the test cycle were found to exceed them on the
        road, because their software detected the test <Cite id="thompson2014" />. Telemetry controlled by a toolmaker
        is a claim by an interested party, which matters where toolmakers also host the commons or shape its
        definitions.
      </p>
      <p>
        <strong>Non-stationarity.</strong> Workers learn, tools wear, materials vary by batch, and autonomous agents
        change with each version. Effects estimated as fixed then describe an average over a period. Allowing effects
        to drift with time or version addresses this at a cost in precision, and the identity of an autonomous agent
        across versions has to be defined in the commons. Where autonomous agents perform a step at high volume, they
        dominate the records from which its forecast is estimated, and workers are evaluated against a forecast set
        largely by machines, unless the class of agent enters as a partition.
      </p>
      <p>
        <strong>Feedback.</strong> Once scores gate eligibility, the trace records behaviour shaped by those scores, and
        the forecast is trained on it. Indicators used for decisions tend to be corrupted by the pressure they
        create <Cite id="campbell1979" />, and models whose predictions influence the outcomes they predict converge
        to something other than their original target <Cite id="perdomo2020" />. The allocated share of work supplies
        records less shaped by the scores.
      </p>

      <h3>Incentives</h3>
      <p>
        <strong>The ratchet effect.</strong> Because the trace shows what is achievable, workers may withhold output
        to avoid rates being cut <Cite id={['gibbons1987', 'roy1952', 'bouwens2011']} />. A change to the process is credited to whoever made it, across
        the deliveries of those who adopt it (Section 4.6), so improving a step does not lower the innovator&rsquo;s
        return. Workers who
        did not innovate are then evaluated against the tightened forecast, and their standing falls until they adopt
        the practice, for which training is the route. Difficulty is carried by descriptors and conditioned on, so
        harder work is evaluated against a correspondingly harder forecast. The forecast is also drawn from
        peers&rsquo; deliveries, so informal help that improves a colleague&rsquo;s delivery tightens it slightly against
        the helper, a weaker form of the relative evaluation that discourages cooperation <Cite id="lazear1989" />. In a
        large commons one colleague moves the pooled forecast little, and help given within joint work can appear as a
        co-worker effect <Cite id="jaravel2018" />, but help outside recorded work is not credited, and collective
        withholding of the kind Roy documents is a group response that individual credit does not address.
      </p>
      <p>
        <strong>Crediting innovation.</strong> Priority by first recording invites the registration of speculative
        variants, but a variant is credited only with measured gain, so one that changes nothing earns nothing.
        Variants used together share a gain that cannot always be split. Gain measured against the forecast that held
        before a change is confounded with trends and with concurrent changes, which comparison with deliveries not
        using the variant controls. Detecting undeclared adoption from breaks in an agent&rsquo;s effect is itself an
        inference about the agent, subject to the limits on inference in Section 6.4.
      </p>
      <p>
        <strong>Crowding out.</strong> Measuring contribution and rewarding it can displace the intrinsic motivation
        behind it <Cite id={['deci1999', 'benabou2003']} />. A trace the worker co-owns, informing
        decisions rather than making them, is less likely to be experienced as control, but the risk remains where
        reward follows the record closely.
      </p>
      <p>
        <strong>Compelled disclosure.</strong> The unravelling that draws organisations into the commons applies to
        workers too. A worker who withholds their record may be presumed to be hiding a poor one, so co-ownership can
        become disclosure under pressure. Unravelling assumes quality that is verifiable and comparable on one scale,
        so with a record that is multidimensional and estimated with noise it is likely to be partial.
      </p>

      <h3>Governance and law</h3>
      <p>
        <strong>Starting the commons.</strong> The value of the commons grows with participation, so it is low at
        the outset. The interests of parties in hosting it, and the reward for improving it, partly address this.
      </p>
      <p>
        <strong>Definition of outputs and metrics.</strong> The commons fixes what each step outputs and how it is
        measured. A party able to define these could favour its own tools or methods. Where the process is open and
        can be forked, competing variants check this. Forking also fragments the commons, whose value depends on its
        scale. The parties who gain most from the commons, such as toolmakers, are also best placed to bend its
        definitions toward their own products.
      </p>
      <p>
        <strong>Competition law.</strong> Pooling detailed time, cost and material data across competing organisations
        is an exchange of information between competitors, which competition law in the EU, the UK and the United
        States restricts where it facilitates collusion. Sharing workers&rsquo; performance and pay between employers is
        under particular scrutiny, and the United States has withdrawn its earlier safe harbour for such
        exchanges <Cite id="doj2023" />, while the EU&rsquo;s guidelines treat aggregated, historical benchmarking more
        leniently <Cite id="ec2023horizontal" />. A commons spanning an industry would need to aggregate or delay what
        competitors see of one another, which may limit its scale.
      </p>
      <p>
        <strong>Inference beyond performance.</strong> Records can reveal more than performance. Patterns of hours
        and absence may indicate health, pregnancy or union activity. Access to records must be limited to what
        attribution requires.
      </p>
      <p>
        <strong>Equality.</strong> Evaluation against a forecast ranks slower workers lower, including disabled
        workers and those whose hours are shaped by caring responsibilities. Conditioning on descriptors can appear
        neutral while producing disparate impact. Partitions make such differences visible. An agreed accommodation can
        enter as an attribute of the agent, so that the comparison conditions on it and works for the worker as well
        as against them, at the cost to privacy noted above. What is done about remaining differences is a matter
        for the parties and for law.
      </p>
      <p>
        <strong>Allocation.</strong> Allocating a share of work, as a check on choice, removes the choice for that
        share. In some domains, such as healthcare, allocation raises questions of consent and of fairness to those
        allocated, which the parties and the law must settle.
      </p>
      <p>
        <strong>Automating decisions.</strong> TBP remains distinct from algorithmic management only while decisions
        other than eligibility
        remain with the parties. A deployment that automates selection or pay reconstitutes the central controller
        the model avoids.
      </p>
      <p>
        <strong>Residual transaction costs.</strong> TBP does not remove the cost of coordination. The trace must be
        verified, the commons governed and its definitions maintained. It replaces repeated, boundary-specific efforts
        with shared infrastructure.
      </p>
    </>
  );
}
